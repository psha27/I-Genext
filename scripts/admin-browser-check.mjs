import { pathToFileURL, fileURLToPath } from 'node:url'
import { mkdtemp, writeFile, readFile, mkdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { randomBytes } from 'node:crypto'
import assert from 'node:assert/strict'
import express from 'express'
import { createApp } from '../server/src/app.js'
import { createContactStore } from '../server/src/contact.js'
import { createAdminAuth, hashPassword } from '../server/src/admin.js'
import { acknowledgementMessage, startEmailWorker } from '../server/src/email.js'
const { chromium }=await import(process.env.PLAYWRIGHT_MODULE?pathToFileURL(process.env.PLAYWRIGHT_MODULE).href:'playwright')
const directory=await mkdtemp(join(tmpdir(),'igenext-browser-'))
const credentialsFile=join(directory,'admin.json')
const password=randomBytes(24).toString('hex')
await writeFile(credentialsFile,JSON.stringify({username:'admin',...await hashPassword(password)}))
const legacy=Array.from({length:27},(_,i)=>({reference:'LEGACY-'+i,createdAt:'2026-01-01T00:00:00.000Z',name:i===0?'=FORMULA':'Legacy Client '+i,email:'legacy'+i+'@example.com',company:'Legacy Company',area:'Corporate Finance',message:'Legacy message, with a comma.'}))
await writeFile(join(directory,'contact-leads.jsonl'),legacy.map(x=>JSON.stringify(x)).join('\n')+'\n')
const store=createContactStore({DATA_DIR:directory})
const sent=[]
const worker=startEmailWorker(store,{configured:true,send:async lead=>{sent.push(acknowledgementMessage(lead))},close(){}},{intervalMs:50})
const auth=createAdminAuth({credentialsFile})
const app=createApp(store,{auth,emailWorker:worker,emailConfigured:true})
const dist=fileURLToPath(new URL('../client/dist/',import.meta.url))
app.use(express.static(dist))
app.get('/admin',(_req,res)=>res.sendFile(join(dist,'index.html')))
const server=app.listen(0,'127.0.0.1')
await new Promise(resolve=>server.once('listening',resolve))
const base='http://127.0.0.1:'+server.address().port
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await mkdir('test-results',{recursive:true})
try {
  await page.goto(base)
  await page.locator('#contact-name').fill('Prospective Client')
  await page.locator('input[name=email]').fill('client@example.com')
  await page.locator('input[name=company]').fill('Future Company')
  await page.locator('input[name=designation]').fill('Chief Financial Officer')
  await page.locator('input[name=phone]').fill('+91 98765 43210')
  await page.locator('select[name=area]').selectOption('Finance Advisory')
  await page.locator('textarea[name=message]').fill('Please help us improve finance reporting and decision speed.')
  await page.locator('input[name=consent]').check()
  await page.getByRole('button',{name:'Start a conversation',exact:false}).click()
  await page.getByRole('status').filter({hasText:'Your enquiry has been saved.'}).waitFor()
  for(let i=0;i<30 && !sent.length;i++) await new Promise(resolve=>setTimeout(resolve,50))
  assert.equal(sent.length,1)
  assert.match(sent[0].text,/two business days/)
  await writeFile('test-results/acknowledgement-preview.html',sent[0].html)
  await page.locator('#contact').screenshot({path:'test-results/contact-updated.png'})
  const footerLogo=page.locator('.footer-brand .brand img')
  assert.equal(await footerLogo.getAttribute('src'),await page.locator('.site-header .brand img').getAttribute('src'))
  assert.equal(await footerLogo.evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)')
  assert.equal(await footerLogo.evaluate(el=>getComputedStyle(el).padding),'0px')
  await page.locator('footer').screenshot({path:'test-results/footer-logo.png'})
  await page.goto(base+'/admin')
  await page.getByRole('heading',{name:'Welcome back.'}).waitFor()
  assert.equal((await page.request.get(base+'/api/admin/requests/export')).status(),401)
  await page.screenshot({path:'test-results/admin-login.png'})
  await page.locator('input[name=password]').fill('incorrect-password')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'incorrect'}).waitFor()
  await page.locator('input[name=password]').fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByRole('heading',{name:'Company workspace'}).waitFor()
  await page.getByRole('status').filter({hasText:'28 matching requests'}).waitFor()
  await page.getByText('Chief Financial Officer',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Next',exact:true}).click()
  await page.getByText('Page 2 of 2',{exact:true}).waitFor()
  await page.getByPlaceholder('Name, company, email or message').fill('Future Company')
  await page.getByRole('status').filter({hasText:'1 matching requests'}).waitFor()
  await page.getByText('View message',{exact:true}).click()
  await page.getByText('Please help us improve finance reporting and decision speed.',{exact:true}).waitFor()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download all requests (CSV)'}).click()
  const csv=await readFile(await (await download).path(),'utf8')
  assert.match(csv,/Chief Financial Officer/)
  assert.match(csv,/LEGACY-26/)
  assert.match(csv,/'=FORMULA/)
  await page.screenshot({path:'test-results/admin-workspace.png'})
  await page.reload()
  await page.getByRole('heading',{name:'Company workspace'}).waitFor()
  await page.setViewportSize({width:390,height:900})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.screenshot({path:'test-results/admin-mobile.png'})
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.getByRole('heading',{name:'Welcome back.'}).waitFor()
  assert.equal((await page.request.get(base+'/api/admin/requests')).status(),401)
  assert.deepEqual(errors,[])
  console.log('Admin browser checks passed: real isolated contact persistence, new fields, acknowledgement with mocked delivery, login failure/success, pagination, search, full CSV, session reload, logout, mobile layout and matching transparent footer logo. No external emails sent.')
} finally {
  await browser.close();await worker.stop()
  await new Promise(resolve=>server.close(resolve))
  await store.close();await rm(directory,{recursive:true,force:true})
}
